/**
 * 本内容库的调参值 —— `BASELINE_TUNING`（tale-sim，即计划「数值基线」表的落地常量）
 * 打底，只覆写内容层必须自己决定的项。
 *
 * ## 为什么 spread 而不重抄一份
 * 34 个字段抄一遍就会漂移一遍。基线在 tale-sim 里有单测盯着，这里只留**差异**，
 * 差异即「B2 对基线做了什么、为什么」，review 时一眼能看完。
 *
 * ## 覆写项与理由（全部经 50 世冒烟实测校准，见 test/smoke.test.ts）
 * | 字段 | 基线 | 本库 | 为什么 |
 * |---|---|---|---|
 * | `huntPreyIds` | `[]` | 4 个小猎物 | 基线不认识内容 id，**必填**；空表＝狩猎抛错 |
 * | `restHealFlags` | `[]` | `[sick]` | 基线不认识内容 flag。**刻意只放 `sick`**：结算顺序是
 *   「行动本体 → 事件抽取」，休憩在第 1 步就把 flag 摘了，第 2 步抽事件时它已经不在 ——
 *   于是任何 `requiresFlags` 含被休憩治愈 flag 的休憩事件**永远不可能入池**。「旧伤发热」
 *   （requiresFlags: wound）正是这样在 50 世冒烟里一次都没触发，才发现这条顺序陷阱。
 *   现在分工是：病（sick）睡一觉能好，伤（wound）只能靠事件里那场真赌（咬开／以毒攻／硬熬，
 *   硬熬有 18% 会死）或探索池的「倚树而息」 |
 * | `huntFoodGain` | 26 | 30 | 基线下狩猎期望收益（0.49×26）几乎等于每季消耗，
 *   逼玩家每季必猎、没有一季能拿去探索 —— 那就等于把探索池 20 个事件设计掉了 |
 * | `restHungerGain` | 10 | 14 | 同上：基线下休憩净亏 2 点饱食，养伤永远是错的选择 |
 * | `moltThreshold` | 60 | 90 | 基线的 60 是在不知道猎物／事件给多少精气时定的。本库的实际
 *   供给（猎物一次 16〜20、事件 6〜30）在 60 阈值下让一世平均蜕 5.08 件，超出 B5 目标 2〜4
 *   且把 12 器官在中期就掏空；提到 90 后落到 2.80（实测见下），蜕变也才重新有「攒」的手感 |
 *
 * ## B5 联调追加的三项覆写（200 世实测，见 `packages/gen/src/balance-sim.ts`）
 * | 字段 | 基线 | 本库 | 为什么 |
 * |---|---|---|---|
 * | `initialStats.ti` | 20 | **26** | 幼兽血量＝ti。20 血遇上「3＋floor(meng/8)±1」的敌方
 *   伤害，开局两三合就能被一头野雉打死 —— 200 世里 15% 的一世在**三岁前**夭折，其中 10.5%
 *   死于战斗，而这些一世多半连一次蜕变都没见过。ti 提到 26 后三岁前夭折降到 8.5%。
 *   `lifespanMax = 16 + floor(ti/10)` 在 20 与 26 上同为 18 岁，所以寿数上限没被顺手改掉 |
 * | `fleeBase` | 0.5 | **0.58** | 「逃」是低阶段唯一的止损手段，而 0.5 的成功率让它在
 *   最需要它的时候（血剩三成）成了掷硬币；逃跑失败还要白挨一轮，实际是负期望 |
 * | ~~`huntFailCombatChance`~~ | 0.2 | **已删** | M1-P1 追猎屏取消了「狩猎失败掷骰被反咬」这条
 *   分支：现在是否转入搏杀由 `EnemyDef.retaliates` 决定（且**扑之前就在预览里写明**），
 *   不再靠背后掷一次骰。原覆写的用意（别让「饿了去猎」自带一条随机死亡分支）由此结构性达成 |
 *
 * 其余各项一律沿用基线（含 `eventChanceBase` 0.35、`moltThreshold` 之外的全部战斗公式）。
 * **刻意没动 `moltThreshold`**：把它从 90 降到 78 能把「一世未蜕形」压低约 6 个点，代价是蜕
 * 6 件以上的一世多出 7 个点 —— 那头是把 12 器官掏空、build 失去差异。蜕变次数的两极分化
 * （早死的没蜕过／长寿的蜕光）是「精气随寿数线性累积」的结构性结果，单一阈值调不出中间态，
 * 要治得在引擎里做边际递减（M1 议题，不在 B5 范围）。
 *
 * ## 200 世实测（`pnpm -C packages/gen balance -- --profile X`，覆写后）
 * | 画像 | 饿死 | 战死 | 寿终 | 登神 | 均寿 | 活过 8 岁 | 均蜕变 | 三岁前夭折 | 未蜕形 |
 * |---|---|---|---|---|---|---|---|---|---|
 * | cautious（末条抉择＝稳妥） | 58.5% | 8.5% | 33% | 0% | 12.1 | **65%** | 3.19 | 6% | 28.5% |
 * | random（B2 冒烟那个乱点玩家） | 24% | 44.5% | 31.5% | 0% | 11.4 | **61%** | 3.15 | 8.5% | 28.5% |
 * | reckless（首条抉择＝最诱人） | 8.5% | 68% | 23.5% | 0% | 9.9 | 53% | 2.74 | 10.5% | 32.5% |
 *
 * 覆写前的同一批种子（random）是活过 8 岁 50%、三岁前夭折 15%、均寿 9.5 —— 三项覆写换来的
 * 就是这 11 个点。三条 B5 目标（活过 8 岁 ≥60%／平均蜕变 2〜4／登神率 <2%）在 cautious 与
 * random 下全部达标；reckless 的 53% 是**设计使然**（一路挑最贪的分支就该死得早），不为它
 * 放宽数值。cautious 的饿死 58.5% 也是设计的一部分：只挑稳妥选项就会饿 —— 想改的旋钮是
 * `huntFoodGain`／`restHungerGain`，但那会把「食」这个主题一起调没。
 *
 * 两条量测纪律（都是踩出来的）：
 * 1. **小样本不作数**：B2 报告的「活过 8 岁 72%」是 50 世的运气，同策略同种子跑 200 世是 50%。
 *    这个指标在 n=50 上的方差有 ±10 个点，所以调参一律看 200 世。
 * 2. **先怀疑机器玩家**：那 40% 的「一世未蜕形」里有一大半是冒烟策略自己的 bug
 *    （带伤无限休憩，见 test/smoke.test.ts 的 decideAction 注释），不是数值问题。
 */

