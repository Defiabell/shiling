/**
 * 本内容库的调参值 —— `BASELINE_TUNING`（tale-sim，即计划「数值基线」表的落地常量）
 * 打底，只覆写内容层必须自己决定的项。
 *
 * ## 为什么 spread 而不重抄一份
 * 34 个字段抄一遍就会漂移一遍。基线在 tale-sim 里有单测盯着，这里只留**差异**，
 * 差异即「B2 对基线做了什么、为什么」，review 时一眼能看完。
 *
 * ## 覆写项与理由（全部经 50 世冒烟实测校准，见 test/smoke.test.ts）
 * | 字段 | 基线 | 本库 | 为什么 |
 * |---|---|---|---|
 * | `huntPreyIds` | `[]` | 4 个小猎物 | 基线不认识内容 id，**必填**；空表＝狩猎抛错 |
 * | `restHealFlags` | `[]` | `[sick]` | 基线不认识内容 flag。**刻意只放 `sick`**：结算顺序是
 *   「行动本体 → 事件抽取」，休憩在第 1 步就把 flag 摘了，第 2 步抽事件时它已经不在 ——
 *   于是任何 `requiresFlags` 含被休憩治愈 flag 的休憩事件**永远不可能入池**。「旧伤发热」
 *   （requiresFlags: wound）正是这样在 50 世冒烟里一次都没触发，才发现这条顺序陷阱。
 *   现在分工是：病（sick）睡一觉能好，伤（wound）只能靠事件里那场真赌（咬开／以毒攻／硬熬，
 *   硬熬有 18% 会死）或探索池的「倚树而息」 |
 * | `huntFoodGain` | 26 | 30 | 基线下狩猎期望收益（0.49×26）几乎等于每季消耗，
 *   逼玩家每季必猎、没有一季能拿去探索 —— 那就等于把探索池 20 个事件设计掉了 |
 * | `restHungerGain` | 10 | 14 | 同上：基线下休憩净亏 2 点饱食，养伤永远是错的选择 |
 * | `moltThreshold` | 60 | 90 | 基线的 60 是在不知道猎物／事件给多少精气时定的。本库的实际
 *   供给（猎物一次 16〜20、事件 6〜30）在 60 阈值下让一世平均蜕 5.08 件，超出 B5 目标 2〜4
 *   且把 12 器官在中期就掏空；提到 90 后落到 2.80（实测见下），蜕变也才重新有「攒」的手感 |
 *
 * 其余 29 项一律沿用基线（含 `eventChanceBase` 0.35 与全部战斗公式）—— 冒烟数据落在目标
 * 区间内，就不动它们。
 *
 * ## 50 世冒烟实测（test/smoke.test.ts 每次跑都会打印）
 * 饿死 14%／战死 54%／寿终 32%／登神 0%；平均寿数 11.8 岁、平均蜕变 2.80、平均击杀 1.96、
 * 平均血统点 3.48；活过 8 岁 72%（B5 目标 ≥60%）；事件覆盖 43/44（只差登神出口「天命」）。
 * 战死占比过半是那个「乱点抉择的机器玩家」的画像，不是玩家画像 —— B5 用聪明策略重测时会降。
 */

import { BASELINE_TUNING, type TaleTuning } from "@shiling/tale-sim";
import { PREY_IDS } from "./enemies.js";
import { FLAG_SICK } from "./flags.js";

export const TUNING: TaleTuning = {
  ...BASELINE_TUNING,

  // 内容层必填：基线无从预知内容 id
  huntPreyIds: [...PREY_IDS],
  // 只治病不治伤 —— 治伤会让「旧伤发热」永远无法入池，见上文结算顺序陷阱
  restHealFlags: [FLAG_SICK],

  // 让「不狩猎的那一季」在数值上真的存在
  huntFoodGain: 30,
  restHungerGain: 14,

  // 按本库的实际精气供给校准（基线 60 → 一世平均蜕 5 件，太多）
  moltThreshold: 90,
};
