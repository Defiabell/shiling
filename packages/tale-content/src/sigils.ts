/**
 * 世家印记表（4 枚，至多受 2 枚）—— S3 四类血统消费里唯一的**永久数值**加成。
 *
 * 需求正本：`docs/plans/shiling/2026-08-13-liezhuan-build-depth-plan.md` 的「S3 血统元进度」
 * （「世家印记（永久小加成，如每世 +2 灵）；要有多个可选、可叠加但有上限」）。
 *
 * ## 为什么只有 +1、只有两枚、且**没有德那一枚** —— 三个数都是量出来的
 * 计划正本举的例子是「每世 +2 灵」。落地时按那个量做了第一版，然后实测发现
 * **它把 `cautious` 画像顶出了 ≤15% 的成道率护栏**。查下去的根因不是印记太强，是
 * **护栏本来就只剩 0.8 个点的余量**（基线 14.2%，上界 15%）：
 *
 * | 口径（4000 世 `cautious`，se ≈ 0.55 个点） | 成道率 |
 * |---|---|
 * | 不带印记（基线） | **14.3%** |
 * | 骨 体 +2 | 14.7%（+0.4，≈噪声） |
 * | 目 灵 +2 | 14.6%（+0.3，≈噪声） |
 * | 食 起手饱食 +12 | 14.3%（±0） |
 * | 爪 猛 +2 | 15.0%（+0.7，1.3σ） |
 * | **仁 德 +2** | **15.7%（+1.4，2.5σ —— 唯一显著的一枚）** |
 * | 三枚 +2（目仁骨） | 16.6% ✗ |
 * | 三枚 +1（爪仁骨） | 15.3% ✗ |
 *
 * 于是先砍成「+1、至多两枚」。**但那还不够** —— code-reviewer 指出「两枚」只抽查了
 * 十对里的三对，于是把十对全扫了一遍（4000 世），最高的一对（仁＋食）量到 15.1%。
 * 4000 世的 se 是 0.56 个点，10 个读数散在 14.4〜15.1 之间，**分不出是真的还是抖动**
 * —— 中途还差点据此去调「食」的数值（把 12 砍成 6，结果那一对反而读到 15.3%，
 * 正是把噪声写进 tuning 的那种错）。改成 **20000 世**（se 0.25）复量才看清：
 *
 * | 20000 世 `cautious` | 成道率 | 判 |
 * |---|---|---|
 * | 基线（无印记） | **14.2%** | —— |
 * | 目＋骨 | 14.3% | ✓ |
 * | 爪＋目 | 14.8% | ✓ |
 * | 爪＋骨 | 14.8% | ✓ |
 * | 爪＋食 | 14.9% | ✓ |
 * | **仁＋食** | **15.0%** | ✗（贴线） |
 * | **爪＋仁** | **15.4%** | ✗ |
 *
 * **两对越界的都带着「仁」，不带它的四对全在 14.9% 以内** —— 于是德那一枚整个撤掉。
 * 根因不是「德更重要」，是**德的起手值远小于它的门槛**：
 * 起手 meng 10／ling 10／ti 20／**de 5**，而登神要 de 40、归山要 de 60。
 * 一枚 +1 落在德上是起手值的 20%、且直接顶在两条道的门槛上；落在体上只有 5%，
 * 而体根本不是任何一条道的门槛。**四项属性里，德是唯一不能卖的那一项。**
 *
 * ⚠️ 代价说清楚：登神与归山（两条吃德的道）因此没有专属印记。
 * 它们仍各有一枚沾边的（登神→目吃灵，归山→骨吃寿限），但「奔德」这条线买不到东西。
 * 这是护栏与「可买」之间的取舍，owner 若觉得不该这样，要动的是护栏而不是这张表。
 *
 * ## 为什么不干脆做大一点
 * owner 的原话是「积累只让数字变大」—— 那正是这一批要治的病。四类消费里三类给的是
 * **新动作或新信息**（血脉带一件器官、图录开一处门、图鉴知识看清一头兽），
 * 印记是唯一让数字变大的一类。它要回答的是「跨了十世之后我有没有一点点不同」，
 * 不是「我现在很强」—— 而护栏恰好也只允许这么多。
 *
 * ## 四枚 ＝ 三项属性 ＋ 一枚饱食
 * 让「买哪两枚」跟着**你想走哪条道**分岔（奔化灵的买目，奔妖王的买爪）——
 * 这是印记与「摸得着的发展方向」之间的接口。第五枚「食」不动属性而动起手饱食：
 * 头几世的死因压倒性是饿死（`cautious` 4000 世实测 52.7%），而属性一项也治不了它 ——
 * 新玩家的第一枚印记该有一个「让我活得过童年」的选项（而且它实测 ±0，是最安全的一枚）。
 *
 * ⚠️ 这一节是数值，不是文风。改任何一个数都要跑
 * `pnpm -C packages/gen balance --lives 20000 --profile cautious --sigils <两枚 id>` **把 C(4,2)
 * 六对全扫一遍**（不是抽三对，也不是「单枚最强的两枚凑一对」—— 那两条捷径都被实测证伪过）。
 * 500 世的 se 是 1.6 个点、4000 世 0.56 个点，都量不出这里 0.8 个点的预算，见 S3 报告第六节。
 */

